CREATE TABLE paquetes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    destino VARCHAR(90) NOT NULL,
    pais VARCHAR(90) NOT NULL,
    duracion_dias INTEGER NOT NULL CHECK (duracion_dias > 0),
    precio_cop NUMERIC(14,2) NOT NULL CHECK (precio_cop >= 0),
    descripcion VARCHAR(600) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    paquete_id BIGINT NOT NULL REFERENCES paquetes(id),
    nombre_cliente VARCHAR(100) NOT NULL,
    correo_cliente VARCHAR(150) NOT NULL,
    viajeros INTEGER NOT NULL CHECK (viajeros BETWEEN 1 AND 10),
    total_cop NUMERIC(14,2) NOT NULL CHECK (total_cop >= 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA')),
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reservas_paquete_id ON reservas(paquete_id);
